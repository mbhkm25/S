begin
  select jobid into v_jobid from cron.job where jobname='sanad_ops_watch_hourly' limit 1;
  if v_jobid is not null then perform cron.unschedule(v_jobid); end if;
  perform cron.schedule('sanad_ops_watch_hourly','0 * * * *',$cron$select private.run_sanad_ops_watch_snapshot(now(),60);$cron$);
end $$;