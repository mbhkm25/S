create or replace function public.get_business_erp_snapshot_status_v1(p_business_id uuid)
returns jsonb
language plpgsql
security definer
set search_path=''
as $function$
declare
  v_uid uuid := auth.uid();
  v_latest public.business_erp_baseline_runs%rowtype;
begin
  if v_uid is null then raise exception 'authentication_required' using errcode='42501'; end if;
  if not (
    private.user_is_business_owner(p_business_id,v_uid)
    or private.user_is_active_business_member(p_business_id,v_uid)
  ) then
    raise exception 'business_access_denied' using errcode='42501';
  end if;

  select * into v_latest
  from public.business_erp_baseline_runs
  where business_id=p_business_id
    and baseline_kind='logical_backup'
  order by started_at desc
  limit 1;

  if not found then
    return jsonb_build_object(
      'available',false,
      'snapshot_public_id',null,
      'status','not_started',
      'contract_version',1
    );
  end if;

  return jsonb_build_object(
    'available',v_latest.status='completed',
    'snapshot_public_id',v_latest.baseline_public_id,
    'status',v_latest.status,
    'started_at',v_latest.started_at,
    'completed_at',v_latest.completed_at,
    'expected_counts',v_latest.expected_counts,
    'received_counts',v_latest.received_counts,
    'manifest',v_latest.manifest,
    'contract_version',1
  );
end;
$function$;

revoke all on function public.get_business_erp_snapshot_status_v1(uuid) from public,anon;
grant execute on function public.get_business_erp_snapshot_status_v1(uuid) to authenticated;

create or replace function public.get_business_erp_snapshot_table_rows_v1(
  p_business_id uuid,
  p_table_name text,
  p_limit integer default 200,
  p_offset integer default 0
)
returns jsonb
language plpgsql
security definer
set search_path=''
as $function$
declare
  v_uid uuid := auth.uid();
  v_snapshot uuid;
  v_limit integer := least(greatest(coalesce(p_limit,200),1),1000);
  v_offset integer := greatest(coalesce(p_offset,0),0);
  v_items jsonb;
  v_total bigint;
begin
  if v_uid is null then raise exception 'authentication_required' using errcode='42501'; end if;
  if nullif(btrim(p_table_name),'') is null then raise exception 'table_name_required' using errcode='22023'; end if;

  if not (
    private.user_is_business_owner(p_business_id,v_uid)
    or private.user_is_active_business_member(p_business_id,v_uid)
  ) then
    raise exception 'business_access_denied' using errcode='42501';
  end if;

  select baseline_public_id into v_snapshot
  from public.business_erp_baseline_runs
  where business_id=p_business_id
    and baseline_kind='logical_backup'
    and status='completed'
  order by completed_at desc
  limit 1;

  if v_snapshot is null then
    return jsonb_build_object('items','[]'::jsonb,'total',0,'snapshot_public_id',null,'contract_version',1);
  end if;

  select count(*) into v_total
  from public.business_erp_snapshot_rows
  where business_id=p_business_id and snapshot_public_id=v_snapshot and table_name=btrim(p_table_name);

  select coalesce(jsonb_agg(to_jsonb(x) order by x.row_key),'[]'::jsonb)
  into v_items
  from (
    select row_key,row_hash,row_data,captured_at
    from public.business_erp_snapshot_rows
    where business_id=p_business_id
      and snapshot_public_id=v_snapshot
      and table_name=btrim(p_table_name)
    order by row_key
    limit v_limit offset v_offset
  ) x;

  return jsonb_build_object(
    'items',v_items,
    'total',v_total,
    'limit',v_limit,
    'offset',v_offset,
    'snapshot_public_id',v_snapshot,
    'table_name',btrim(p_table_name),
    'contract_version',1
  );
end;
$function$;

revoke all on function public.get_business_erp_snapshot_table_rows_v1(uuid,text,integer,integer) from public,anon;
grant execute on function public.get_business_erp_snapshot_table_rows_v1(uuid,text,integer,integer) to authenticated;
