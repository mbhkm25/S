create table if not exists public.ai_model_pricing (
  model text not null,
  billing_mode text not null default 'standard',
  input_per_million_usd numeric(12,6) not null,
  cached_input_per_million_usd numeric(12,6),
  output_per_million_usd numeric(12,6) not null,
  effective_from timestamptz not null default now(),
  effective_to timestamptz,
  source_url text,
  notes text,
  primary key (model, billing_mode, effective_from)
);

alter table public.ai_model_pricing enable row level security;
revoke all on public.ai_model_pricing from anon, authenticated;

create table if not exists public.ai_usage_ledger (
  id bigint generated by default as identity primary key,
  occurred_at timestamptz not null default now(),
  request_id text,
  operation_id uuid references public.operations(id) on delete set null,
  source text not null,
  purpose text not null,
  environment text not null default 'production',
  model text not null,
  billing_mode text not null default 'standard',
  status text not null default 'completed',
  prompt_tokens bigint not null default 0,
  cached_tokens bigint not null default 0,
  candidate_tokens bigint not null default 0,
  thinking_tokens bigint not null default 0,
  billed_output_tokens bigint generated always as (candidate_tokens + thinking_tokens) stored,
  total_tokens bigint not null default 0,
  input_cost_usd numeric(18,9) not null default 0,
  cached_input_cost_usd numeric(18,9) not null default 0,
  output_cost_usd numeric(18,9) not null default 0,
  estimated_cost_usd numeric(18,9) generated always as (input_cost_usd + cached_input_cost_usd + output_cost_usd) stored,
  latency_ms integer,
  usage_metadata jsonb,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create unique index if not exists ai_usage_ledger_request_id_uidx on public.ai_usage_ledger(request_id) where request_id is not null;
create index if not exists ai_usage_ledger_occurred_at_idx on public.ai_usage_ledger(occurred_at desc);
create index if not exists ai_usage_ledger_operation_id_idx on public.ai_usage_ledger(operation_id);
create index if not exists ai_usage_ledger_purpose_idx on public.ai_usage_ledger(purpose, occurred_at desc);

alter table public.ai_usage_ledger enable row level security;
revoke all on public.ai_usage_ledger from anon, authenticated;

